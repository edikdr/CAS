#!/usr/bin/env python3
"""
Bake the words for every track into arctic-monkeys/js/lyrics-data.js.

The site does not need this. It fetches the words at runtime — its own
/api/lyrics if a function is deployed, and LRCLIB straight from the
browser if not — and every song's words appear either way. Run this when
you would rather they were already there:

  * they are on screen the frame a window opens, with no network at all
  * a host that blocks the outbound calls, or a visitor behind something
    that does, still gets the whole song
  * the timings come with them, so the follow-along marker runs the length
    of the track rather than the thirty seconds a preview covers

Sources, neither of which needs a key:

  LRCLIB      https://lrclib.net      plain text and a time-stamped LRC
  lyrics.ovh  https://api.lyrics.ovh  plain text, for what LRCLIB lacks

Usage:
    python3 tools/fetch_lyrics.py                 # every track in data.js
    python3 tools/fetch_lyrics.py --only 505      # one, by name or fragment
    python3 tools/fetch_lyrics.py --refresh       # re-ask for what is there

Already-fetched tracks are kept and skipped, so a second run only picks up
what was missed. --refresh asks again for everything.

The words belong to their publishers. Committing them and putting them on
a public site is your decision and your responsibility, which is why this
is a step you take rather than one already taken for you.
"""

import argparse
import json
import os
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA_JS = os.path.join(ROOT, 'arctic-monkeys', 'js', 'data.js')
OUT_JS = os.path.join(ROOT, 'arctic-monkeys', 'js', 'lyrics-data.js')

ARTIST = 'Arctic Monkeys'
UA = 'ArcticMonkeysFanSite/1.0 ( fan project, non-commercial )'

HEADER = """/* Generated by tools/fetch_lyrics.py — do not edit by hand.

   The words for every track, so the site has them without a network.
   Read only if present; see js/lyrics.js for the order the sources are
   asked in. Delete this file and the site falls back to fetching them,
   which also works.

   The words belong to their publishers.
"""


# ----------------------------------------------------------------- http

def get(url, tries=3):
    """A JSON GET that treats a 404 as an answer rather than a failure."""
    for attempt in range(tries):
        try:
            req = urllib.request.Request(url, headers={'User-Agent': UA})
            with urllib.request.urlopen(req, timeout=30) as r:
                return json.loads(r.read().decode('utf-8'))
        except urllib.error.HTTPError as e:
            if e.code == 404:
                return None
            if attempt == tries - 1:
                print(f'  ! {e.code} {url[:90]}', file=sys.stderr)
        except Exception as e:
            if attempt == tries - 1:
                print(f'  ! {e} {url[:90]}', file=sys.stderr)
        time.sleep(1.5 * (attempt + 1))
    return None


# ------------------------------------------------------------ read data.js

def read_tracks():
    """(album title, track name) for everything in the discography.

    The same narrow regex fetch_am_data.py uses: only titles are needed,
    which is not worth a JS parser.
    """
    with open(DATA_JS, encoding='utf-8') as f:
        src = f.read()
    block = src[src.index('const ALBUMS'):src.index('const SINGLES')]
    out = []
    for chunk in block.split('\n  {\n')[1:]:
        title = re.search(r"title:\s*(['\"])(.*?)\1,", chunk)
        if not title:
            continue
        album = title.group(2).replace("\\'", "'")
        for m in re.finditer(r"\{\s*name:\s*(['\"])(.*?)\1,", chunk):
            out.append((album, m.group(2).replace("\\'", "'")))
    return out


def read_existing():
    """Whatever a previous run left behind, so it is not asked for twice."""
    if not os.path.exists(OUT_JS):
        return {}
    with open(OUT_JS, encoding='utf-8') as f:
        src = f.read()
    i = src.find('{', src.find('const LYRICS_DATA'))
    if i < 0:
        return {}
    try:
        return (json.loads(src[i:src.rindex('}') + 1]) or {}).get('tracks') or {}
    except Exception:
        return {}      # a placeholder, or something hand-edited


# ------------------------------------------------------------- providers

def lrclib(track, album):
    """LRCLIB. `get` is the exact match; `search` catches the rest.

    A time-stamped result is worth more than a plain one, so it is
    preferred even when it is not the first thing that came back.
    """
    def best(rows):
        if rows is None:
            return None
        rows = rows if isinstance(rows, list) else [rows]
        return (next((r for r in rows if r and r.get('syncedLyrics')), None)
                or next((r for r in rows if r and r.get('plainLyrics')), None))

    exact = urllib.parse.urlencode({
        'track_name': track, 'artist_name': ARTIST, 'album_name': album})
    hit = best(get(f'https://lrclib.net/api/get?{exact}'))
    if not hit:
        loose = urllib.parse.urlencode({'track_name': track, 'artist_name': ARTIST})
        hit = best(get(f'https://lrclib.net/api/search?{loose}'))
    if not hit:
        return None
    return {
        'track': hit.get('trackName') or track,
        'duration': hit.get('duration') or 0,
        'synced': hit.get('syncedLyrics') or None,
        'plain': hit.get('plainLyrics') or None,
        'source': 'lrclib',
    }


def ovh(track):
    """lyrics.ovh: plain words, no timings, for what LRCLIB has not got."""
    url = ('https://api.lyrics.ovh/v1/'
           + urllib.parse.quote(ARTIST) + '/' + urllib.parse.quote(track))
    body = get(url, tries=2)
    words = (body or {}).get('lyrics') or ''
    words = words.strip()
    if len(words) < 40:
        return None
    return {'track': track, 'duration': 0, 'synced': None,
            'plain': words, 'source': 'lyrics.ovh'}


# ------------------------------------------------------------------ main

def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--only', help='one track, by name or a fragment of it')
    ap.add_argument('--refresh', action='store_true',
                    help='ask again for tracks already in the file')
    args = ap.parse_args()

    pairs = read_tracks()
    if args.only:
        needle = args.only.lower()
        pairs = [p for p in pairs if needle in p[1].lower()]
        if not pairs:
            sys.exit(f'no track matching {args.only!r}')

    have = {} if args.refresh else read_existing()
    print(f'{len(pairs)} tracks · {len(have)} already fetched')

    fetched = timed = missing = 0
    for album, track in pairs:
        if track in have and have[track].get('plain' if not have[track].get('synced') else 'synced'):
            continue
        rec = lrclib(track, album) or ovh(track)
        if not rec:
            missing += 1
            print(f'  — {track}')
            continue
        have[track] = rec
        fetched += 1
        if rec['synced']:
            timed += 1
        print(f'  ✓ {track}  ({rec["source"]}{", timed" if rec["synced"] else ""})')
        time.sleep(0.4)      # LRCLIB is somebody's server, not a CDN

    payload = {
        'generated': time.strftime('%Y-%m-%d'),
        'source': 'lrclib.net, api.lyrics.ovh',
        'tracks': dict(sorted(have.items())),
    }
    body = json.dumps(payload, ensure_ascii=False, indent=1)
    with open(OUT_JS, 'w', encoding='utf-8') as f:
        f.write(HEADER)
        f.write(f'   {len(have)} tracks, fetched {payload["generated"]}. */\n')
        f.write(f'const LYRICS_DATA = {body};\n')

    print(f'\nwrote {os.path.relpath(OUT_JS, ROOT)} — '
          f'{len(have)} tracks total, {fetched} new, {timed} timed, {missing} not found')
    if missing:
        print('Tracks with nothing baked still resolve at runtime, or fall '
              'back to the cue points in data.js.')


if __name__ == '__main__':
    main()
