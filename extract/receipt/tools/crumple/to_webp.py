#!/usr/bin/env python3
"""
Compress the rendered crumple frames.

Crops every stage of an album to one shared bounding box — shared so the
frames still line up when the site cross-fades between them — then writes
webp and removes the PNGs.

    python3 tools/crumple/to_webp.py [--quality 80] [--keep-png]
"""

import argparse
import json
import os
import shutil
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FRAMES = os.path.join(ROOT, 'arctic-monkeys', 'assets', 'crumple')
PAD = 12


def manifest_only():
    """Rebuild the manifest from webp already on disk, keeping the flat
    rect from the existing manifest (meta.json is gone by then)."""
    out = os.path.join(ROOT, 'arctic-monkeys', 'js', 'crumple-manifest.js')
    with open(out, encoding='utf-8') as fh:
        old = json.loads(fh.read().split('const CRUMPLE = ', 1)[1].rstrip().rstrip(';'))

    for album, entry in old.items():
        d = os.path.join(FRAMES, album)
        # trust the files, not the old list — frames may have been thinned
        present = sorted(
            (int(f[:-5]) for f in os.listdir(d) if f.endswith('.webp')),
            reverse=True)
        boxes = {}
        for pct in present:
            bb = Image.open(os.path.join(d, f'{pct}.webp')).convert('RGBA').getbbox()
            bb = bb or (0, 0, 1, 1)
            boxes[str(pct)] = [bb[0], bb[1], bb[2] - bb[0], bb[3] - bb[1]]
        entry['stages'] = present
        entry['boxes'] = boxes
        print(f'{album:8s} {len(present)} frames')

    write_manifest(old, out)
    print(f'\nrewrote {out}')
    return 0


def write_manifest(manifest, out):
    with open(out, 'w', encoding='utf-8') as fh:
        fh.write('/* Generated by tools/crumple/to_webp.py — do not edit.\n')
        fh.write('   Frame sizes, where the flat sheet sits inside each frame,\n')
        fh.write('   and what each stage actually covers — the site uses these\n')
        fh.write('   to lay the frames over the live receipt and to size the\n')
        fh.write('   column. Absent means the site just shows a flat receipt. */\n')
        fh.write('const CRUMPLE = ')
        json.dump(manifest, fh, ensure_ascii=False, indent=1)
        fh.write(';\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--quality', type=int, default=80)
    ap.add_argument('--keep-png', action='store_true')
    ap.add_argument('--manifest-only', action='store_true',
                    help='rebuild crumple-manifest.js from webp already on disk')
    args = ap.parse_args()

    if not os.path.isdir(FRAMES):
        print('no frames — run render.mjs first', file=sys.stderr)
        return 1

    if args.manifest_only:
        return manifest_only()

    total_before = total_after = 0
    manifest = {}

    for album in sorted(os.listdir(FRAMES)):
        d = os.path.join(FRAMES, album)
        if not os.path.isdir(d) or album.startswith('_'):
            continue
        pngs = sorted((f for f in os.listdir(d) if f.endswith('.png')),
                      key=lambda f: -int(f[:-4]))
        if not pngs:
            continue

        # one box for every stage, so nothing shifts between frames
        box = None
        images = {}
        for f in pngs:
            im = Image.open(os.path.join(d, f)).convert('RGBA')
            images[f] = im
            bb = im.getbbox()
            box = bb if box is None else (
                min(box[0], bb[0]), min(box[1], bb[1]),
                max(box[2], bb[2]), max(box[3], bb[3]))

        w, h = next(iter(images.values())).size
        box = (max(0, box[0] - PAD), max(0, box[1] - PAD),
               min(w, box[2] + PAD), min(h, box[3] + PAD))

        # where the flat sheet sits inside the cropped frame — the site
        # uses this to lay the frames exactly over the live receipt
        meta_path = os.path.join(d, 'meta.json')
        if os.path.exists(meta_path):
            with open(meta_path, encoding='utf-8') as fh:
                meta = json.load(fh)
            flat = meta['flat']
            manifest[album] = {
                'frame': [box[2] - box[0], box[3] - box[1]],
                'flat': [round(flat['x'] - box[0], 2), round(flat['y'] - box[1], 2),
                         round(flat['w'], 2), round(flat['h'], 2)],
                'stages': sorted((int(f[:-4]) for f in pngs), reverse=True),
                # what each stage actually covers, so the column can shrink
                # around a balled receipt instead of leaving a hole
                'boxes': {f[:-4]: [round(v, 1) for v in
                                   (lambda b: (b[0], b[1], b[2] - b[0], b[3] - b[1]))(
                                       images[f].crop(box).getbbox() or (0, 0, 1, 1))]
                          for f in pngs},
            }
            if not args.keep_png:
                os.remove(meta_path)

        for f, im in images.items():
            src = os.path.join(d, f)
            dst = src[:-4] + '.webp'
            total_before += os.path.getsize(src)
            im.crop(box).save(dst, 'WEBP', quality=args.quality, method=6)
            total_after += os.path.getsize(dst)
            if not args.keep_png:
                os.remove(src)

        print(f'{album:8s} {len(pngs):2d} frames  '
              f'{box[2]-box[0]}x{box[3]-box[1]}')

    if manifest:
        out = os.path.join(ROOT, 'arctic-monkeys', 'js', 'crumple-manifest.js')
        write_manifest(manifest, out)
        print(f'\nwrote {out}')

    tex = os.path.join(FRAMES, '_tex')
    if os.path.isdir(tex) and not args.keep_png:
        shutil.rmtree(tex)          # textures are an intermediate, not an asset

    if total_before:
        print(f'\n{total_before/1e6:.1f} MB PNG -> {total_after/1e6:.1f} MB webp '
              f'({100*total_after/total_before:.0f}%)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
