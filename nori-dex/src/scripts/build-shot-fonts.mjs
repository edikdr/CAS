/* Generates js/shot-fonts.js: the fonts in fonts/ as data URLs, used only by photo mode.
   Run: node scripts/build-shot-fonts.mjs (after changing files in fonts/). */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const LATIN = 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD';
const FACES = [
  ['Nunito', '500 900', 'nunito-latin.woff2', LATIN],
  ['Tiny5', '400', 'tiny5.woff2', null],
];
const b64 = (f) => readFileSync(join(root, 'fonts', f)).toString('base64');
let css = '';
for (const [family, weight, file, range] of FACES) {
  if (!existsSync(join(root, 'fonts', file))) continue;
  css += `@font-face{font-family:'${family}';font-weight:${weight};src:url(data:font/woff2;base64,${b64(file)}) format('woff2');${range ? 'unicode-range:' + range + ';' : ''}}\n`;
}
writeFileSync(join(root, 'js', 'shot-fonts.js'), `/* Generated by scripts/build-shot-fonts.mjs: fonts as data URLs, used only for photo mode. */\nwindow.PL = window.PL || {};\nPL.shotFontsCSS = ${JSON.stringify(css)};\n`);
console.log('js/shot-fonts.js written,', Math.round(css.length / 1024), 'KB');
