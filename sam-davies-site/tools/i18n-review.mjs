// Writes the CORE section of docs/i18n-review.md: every ES and CA string core wrote, reviewed:false.
// Only the block between the core markers is replaced, so the UI layer's appended section survives.
// Usage: node tools/i18n-review.mjs
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { ROOT, SITE, readJSON } from './lib.mjs';
import { TIMELINE_TEXT } from './make-data.mjs';

const OUT = path.join(ROOT, 'docs/i18n-review.md');
const BEGIN = '<!-- core:begin (generated by tools/i18n-review.mjs — do not edit inside) -->';
const END = '<!-- core:end -->';
const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const flat = (v) => (v && typeof v === 'object' ? Object.entries(v).map(([k, x]) => `${k}: ${x}`).join(' · ') : v);

const rows = [];
const add = (source, key, en, es, ca) => rows.push(`| ${source} | \`${key}\` | ${esc(flat(en))} | ${esc(flat(es))} | ${esc(flat(ca))} | false |`);

const core = Object.fromEntries(await Promise.all(['en', 'es', 'ca'].map(async (l) => [l, await readJSON(path.join(SITE, `i18n/core.${l}.json`))])));
for (const key of Object.keys(core.en)) add('i18n/core', key, core.en[key], core.es[key], core.ca[key]);
const quiz = await readJSON(path.join(ROOT, 'tools/quiz-templates.json'));
for (const [kind, t] of Object.entries(quiz)) {
  if (kind.startsWith('_')) continue;
  for (const part of ['question', 'explain']) add('tools/quiz-templates', `${kind}.${part}`, t[part].en, t[part].es, t[part].ca);
}
for (const [key, t] of Object.entries(TIMELINE_TEXT)) add('tools/make-data (timeline)', key, t.en, t.es, t.ca);

const block = [BEGIN, '',
  '## Core strings (written by the core run)', '',
  `${rows.length} entries. Register: ES neutral Peninsular, informal *tú*; CA standard (Barcelona), informal *tu*.`,
  'Song titles, release titles, artist names and lyrics are never translated. Generated quiz/timeline text is',
  'filled from these templates (`site/data/quiz.json`, `site/data/timeline.json`).', '',
  '| source | key | EN | ES | CA | reviewed |', '|---|---|---|---|---|---|', ...rows, '', END].join('\n');

let doc = await readFile(OUT, 'utf8').catch(() => '');
if (!doc.includes(BEGIN)) {
  doc = ['# i18n review', '',
    '**Every ES and CA string below needs a native-speaker / artist review before any public launch.**',
    'Set `reviewed` to `true` per row once checked (and fix the source file, then regenerate data).', '',
    block, '',
    '## UI strings (appended by the UI run)', '', '_UI layer: append your ES/CA strings below this line with `reviewed: false`._', ''].join('\n');
} else {
  doc = doc.slice(0, doc.indexOf(BEGIN)) + block + doc.slice(doc.indexOf(END) + END.length);
}
await writeFile(OUT, doc);
console.log(`docs/i18n-review.md: ${rows.length} core entries (reviewed:false)`);
