// Match extracted preview files to meta.json by normalized title (+ collection), never by raw name.
// Usage: node tools/match-audio.mjs --raw .cache/raw [--meta .cache/raw/meta.json] [--out site/media/audio]
// Writes site/media/audio/<trackId>.m4a and docs/match-report.md; exits 1 on duplicate/unmatched/ambiguous.
import { readdir, copyFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { args, ROOT, SITE, readJSON, writeJSON, decodeMangled, normTitle, splitArtists, ffprobeDuration } from './lib.mjs';

export async function matchAudio({ raw, meta, out = path.join(SITE, 'media/audio'), copy = true, report = true }) {
  const tracks = await readJSON(meta);
  const files = [];
  async function walk(dir) {
    for (const e of await readdir(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) await walk(p);
      else if (/\.m4a$/i.test(e.name)) files.push(p);
    }
  }
  for (const top of ['Singles', 'EPs', 'Features', 'Albums']) {
    try { await walk(path.join(raw, top)); } catch { /* folder may be missing or empty (Albums.zip is) */ }
  }

  const problems = [];
  const warnings = [];
  const matched = new Map(); // trackId → file
  const rows = [];
  for (const file of files) {
    const rel = path.relative(raw, file);
    const [top, ...rest] = rel.split(path.sep);
    const base = decodeMangled(path.basename(file, path.extname(file)));
    let title = base, collectionHint = null, artistHint = null;
    if (top === 'EPs' && rest.length > 1) {
      collectionHint = decodeMangled(rest[0]);
      title = base.replace(/^\d+\s*-\s*/, '');
    } else if (top === 'Features' || top === 'Albums') {
      const i = base.indexOf(' - ');
      if (i > 0) { artistHint = base.slice(0, i); title = base.slice(i + 3); }
    }
    let cands = tracks.filter((t) => normTitle(t.trackName) === normTitle(title));
    if (cands.length > 1 && collectionHint) cands = cands.filter((t) => normTitle(t.collectionName) === normTitle(collectionHint));
    if (cands.length > 1 && artistHint) {
      const hint = new Set(splitArtists(artistHint).map((a) => a.toLowerCase()));
      cands = cands.filter((t) => splitArtists(t.artistName).some((a) => hint.has(a.toLowerCase())));
    }
    if (cands.length === 0) { problems.push(`UNMATCHED file: ${rel}`); rows.push({ rel, status: 'unmatched' }); continue; }
    if (cands.length > 1) { problems.push(`AMBIGUOUS file: ${rel} → ${cands.map((c) => c.trackId).join(', ')}`); rows.push({ rel, status: 'ambiguous' }); continue; }
    const t = cands[0];
    if (matched.has(t.trackId)) { problems.push(`DUPLICATE: ${rel} and ${path.relative(raw, matched.get(t.trackId))} → ${t.trackId}`); continue; }
    matched.set(t.trackId, file);
    const duration = ffprobeDuration(file);
    if (duration < 29.5 || duration > 30.5) warnings.push(`DURATION ${duration.toFixed(2)} s: ${rel}`);
    rows.push({ rel, status: 'ok', trackId: t.trackId, title: t.trackName, collection: t.collectionName, duration: +duration.toFixed(2) });
  }
  for (const t of tracks) if (!matched.has(t.trackId)) problems.push(`UNMATCHED track: ${t.trackId} “${t.trackName}” (${t.collectionName})`);

  if (copy) {
    await mkdir(out, { recursive: true });
    for (const [id, file] of matched) await copyFile(file, path.join(out, `${id}.m4a`));
  }
  if (report) {
    const md = [
      '# Audio match report', '', `Generated by \`tools/match-audio.mjs\`. Files: ${files.length} · meta tracks: ${tracks.length} · matched: ${matched.size}.`, '',
      warnings.length ? '## Warnings\n\n' + warnings.map((p) => `- ${p}`).join('\n') + '\n' : '',
      problems.length ? '## Problems\n\n' + problems.map((p) => `- ${p}`).join('\n') + '\n' : '## Problems\n\nNone.\n',
      '## Matches', '', '| File | trackId | Title | Collection | s |', '|---|---|---|---|---|',
      ...rows.filter((r) => r.status === 'ok').sort((a, b) => a.rel.localeCompare(b.rel))
        .map((r) => `| ${r.rel.replace(/\|/g, '\\|')} | ${r.trackId} | ${r.title.replace(/\|/g, '\\|')} | ${r.collection.replace(/\|/g, '\\|')} | ${r.duration} |`),
      '',
    ].join('\n');
    await writeFile(path.join(ROOT, 'docs/match-report.md'), md);
    await writeJSON(path.join(ROOT, '.cache/match.json'), Object.fromEntries([...matched].map(([id, f]) => [id, path.relative(raw, f)])));
  }
  return { matched, problems, warnings, files };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const a = args();
  const raw = path.resolve(a.raw || path.join(ROOT, '.cache/raw'));
  const res = await matchAudio({ raw, meta: path.resolve(a.meta || path.join(raw, 'meta.json')), out: a.out && path.resolve(a.out) });
  console.log(`matched ${res.matched.size}/${res.files.length} files`);
  if (res.warnings.length) console.warn(res.warnings.join('\n'));
  if (res.problems.length) { console.error(res.problems.join('\n')); process.exit(1); }
}
