#!/usr/bin/env python3
"""Generate js/assets.js: an explicit key -> path map of every asset.
The single-file builder rewrites the values in this map to data URIs."""
import pathlib, json

root = pathlib.Path(__file__).resolve().parent.parent
files = sorted(p for p in (root / 'assets').rglob('*.webp'))
entries = []
for p in files:
    rel = p.relative_to(root).as_posix()          # assets/cut/eye.webp
    key = rel[len('assets/'):].rsplit('.', 1)[0]  # cut/eye
    entries.append((key, rel))

lines = [
    '/* ============================================================',
    '   Asset registry — generated by tools/gen_assets.py',
    '   Keys are stable; values are rewritten to data: URIs by',
    '   tools/build_single.py when producing the single-file build.',
    '   ============================================================ */',
    '',
    'const ASSET = {',
]
for key, rel in entries:
    lines.append(f"  {json.dumps(key)}: {json.dumps(rel)},")
lines += [
    '};',
    '',
    'function asset(key) {',
    '  const v = ASSET[key];',
    '  if (!v) console.warn("[assets] missing key:", key);',
    '  return v || "";',
    '}',
    '',
]
(root / 'js' / 'assets.js').write_text('\n'.join(lines), encoding='utf-8')
print(f'wrote js/assets.js with {len(entries)} assets')
